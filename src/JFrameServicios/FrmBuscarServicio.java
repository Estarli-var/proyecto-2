    private void cargarTabla(ArrayList<Servicio> lista) {
    DefaultTableModel model = (DefaultTableModel) tblServicios.getModel();
    model.setRowCount(0);
    for (Servicio s : lista) {
        Object[] fila = {
            s.getCodigo(),
            s.getNombre(),
            s.getDescripcion(),
            String.format("₡%.2f", s.getPrecio())
        };
        model.addRow(fila);
    }
}


