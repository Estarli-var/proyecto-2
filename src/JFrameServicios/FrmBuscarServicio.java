    private void btnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarActionPerformed
        // TODO add your handling code here:
        int filaSeleccionada = tblServicios.getSelectedRow();
    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Debe seleccionar una fila de la tabla.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }
    int codigo = (int) tblServicios.getValueAt(filaSeleccionada, 0);
    Servicio seleccionado = controladorS.buscarServicio(codigo);
    if (seleccionado != null && vistaPadre != null) {
        vistaPadre.cargarDatosServicio(seleccionado);
        this.dispose(); 
    }
    }//GEN-LAST:event_btnSeleccionarActionPerformed

